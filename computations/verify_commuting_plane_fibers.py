"""Check the two ranks of the linear lift on a reduced and an attached residual point."""
import sympy as sp

x, y, z = variables = sp.symbols('x y z')
monomials = [x**i*y**j*z**(3-i-j) for i in range(4) for j in range(4-i)]


def columns(forms, degree):
    return sp.Matrix([[sp.Poly(f, *variables).coeff_monomial(m) for f in forms] for m in degree])


def check(triangle, l, m, expected):
    matrix = columns([l*q for q in triangle]+[m*q for q in triangle], monomials)
    assert matrix.rank() == expected
    return expected


if __name__ == '__main__':
    # Three coordinate points. With p=(1,1,1) the kernel vanishes.
    print("detached", check([x*y, x*z, y*z], x-y, y-z, 6))
    # With p=(1,0,0) there is one socle correction, generated by x.
    print("attached", check([x*y, x*z, y*z], y, z, 5))
